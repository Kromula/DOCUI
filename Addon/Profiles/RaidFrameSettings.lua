-- Import function
-- RaidFrameSettings uses local LibDeflate/AceSerializer libs; no public import API is exposed,
-- so we replicate the same decode -> decompress -> deserialize -> apply logic here.
function DOCUI.Profiles.RaidFrameSettings:Import()
    if not C_AddOns.IsAddOnLoaded("RaidFrameSettings") then
        return false, "Raid Frame Settings is not installed or enabled."
    end

    local rfs = _G["RaidFrameSettings"]
    if not rfs or not rfs.db then
        return false, "RaidFrameSettings database not found. Try /reload first."
    end

    local LibDeflate = LibStub and LibStub("LibDeflate", true)
    local AceSerializer = LibStub and LibStub("AceSerializer-3.0", true)

    if not LibDeflate then
        return false, "LibDeflate not found. Ensure RaidFrameSettings is loaded."
    end
    if not AceSerializer then
        return false, "AceSerializer-3.0 not found. Ensure RaidFrameSettings is loaded."
    end

    local success, err = pcall(function()
        local decoded = LibDeflate:DecodeForPrint(self.importString)
        if not decoded then error("Decoding failed - string may be corrupt.") end

        local decompressed = LibDeflate:DecompressZlib(decoded)
        if not decompressed then error("Decompression failed - string may be corrupt.") end

        local valid, data = AceSerializer:Deserialize(decompressed)
        if not valid or not data then error("Deserialization failed - string may be corrupt.") end

        for k, v in pairs(data) do
            if type(v) == "table" then
                rfs.db.profile[k] = CopyTable(v)
            else
                rfs.db.profile[k] = v
            end
        end
    end)

    if not success then
        return false, "Failed to import: " .. tostring(err)
    end

    return true, "Raid Frame Settings profile imported successfully!"
end
